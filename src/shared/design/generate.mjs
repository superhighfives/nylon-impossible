#!/usr/bin/env node
/**
 * Generates platform token files from tokens.json:
 *
 *   src/web/src/styles/tokens.css                       CSS custom properties
 *   src/ios/Nylon Impossible/Nylon Impossible/Theme/Theme.swift
 *
 *   node src/shared/design/generate.mjs           write both files
 *   node src/shared/design/generate.mjs --check   exit 1 if either is stale
 *
 * Plain Node, no dependencies. The render functions are exported so the token
 * test can check them without touching the filesystem.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = join(here, "../../..");
export const TOKENS_PATH = join(here, "tokens.json");
export const OUTPUTS = {
  css: join(REPO_ROOT, "src/web/src/styles/tokens.css"),
  swift: join(
    REPO_ROOT,
    "src/ios/Nylon Impossible/Nylon Impossible/Theme/Theme.swift",
  ),
};

const HEADER_LINES = [
  "Generated by src/shared/design/generate.mjs from tokens.json — do not edit.",
  "Change tokens.json, then run `bun run tokens`. `bun run tokens:check` fails CI",
  "when this file is stale.",
];

export function loadTokens() {
  return JSON.parse(readFileSync(TOKENS_PATH, "utf8"));
}

const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
/**
 * A colour's alpha in one appearance: one number for both, or `{ light, dark }`
 * when they differ. Undefined when it has none.
 */
const alphaOf = (c, mode) =>
  typeof c.alpha === "object" ? c.alpha[mode] : c.alpha;
/** A colour value as CSS hex, with the token's alpha (if any) as a fourth byte. */
const cssHex = (hex, c, mode = "light") => {
  const base = hex.toLowerCase();
  const alpha = alphaOf(c, mode);
  if (alpha === undefined) return base;
  const byte = Math.round(alpha * 255)
    .toString(16)
    .padStart(2, "0");
  return `${base}${byte}`;
};
const entries = (obj) =>
  Object.entries(obj).filter(([key]) => !key.startsWith("$"));

/** The sheet's shadow at one appearance's opacity. */
const cssSheetShadow = (sheet, mode) => {
  const { x, y, blur } = sheet.shadow;
  const pct = Math.round(sheet.shadowOpacity[mode] * 100);
  return `${x / 16}rem ${y / 16}rem ${blur / 16}rem color-mix(in srgb, black ${pct}%, transparent)`;
};

function cssFontFamily(tokens, fontKey) {
  const font = tokens.font[fontKey];
  const system = "ui-sans-serif, system-ui, -apple-system, sans-serif";
  return font.family === "system" ? system : `"${font.family}", ${system}`;
}

/** tokens.json → tokens.css */
export function renderCss(tokens) {
  const out = [];
  out.push("/*", ...HEADER_LINES.map((l) => ` * ${l}`), " */", "");
  out.push(
    "/* Every token is prefixed --n- so it can't collide with Tailwind's own",
    "   theme variables. Dark values apply under the same class-based variant",
    "   the app uses (`.dark` on <html>, set by SSR and ThemeSync). */",
    ":root {",
  );
  for (const [name, c] of entries(tokens.color)) {
    out.push(`  --n-color-${kebab(name)}: ${cssHex(c.light, c)};`);
  }
  out.push("");
  for (const [name] of entries(tokens.font)) {
    out.push(`  --n-font-${kebab(name)}: ${cssFontFamily(tokens, name)};`);
  }
  out.push("");
  // No type or space: the web doesn't read them (see their $comment).
  for (const [name, px] of entries(tokens.radius)) {
    out.push(`  --n-radius-${kebab(name)}: ${px / 16}rem;`);
  }
  out.push("");
  const { sheet } = tokens;
  for (const name of ["radius", "inset", "overlap", "slide"]) {
    out.push(`  --n-sheet-${name}: ${sheet[name] / 16}rem;`);
  }
  out.push(`  --n-sheet-recede: ${sheet.recede};`);
  out.push(`  --n-sheet-shadow: ${cssSheetShadow(sheet, "light")};`);
  out.push("");
  const { board } = tokens;
  for (const name of [
    "columnMinWidth",
    "columnMaxWidth",
    "sectionOutlineWidth",
  ]) {
    out.push(`  --n-board-${kebab(name)}: ${board[name] / 16}rem;`);
  }
  // The web's tile only joins up with its neighbours at 45° (or 135°, 225°, 315°); any
  // other angle would draw a broken hatch, so fail here instead.
  if (board.hatch.angle % 90 !== 45) {
    throw new Error(
      `board.hatch.angle must be 45, 135, 225 or 315, not ${board.hatch.angle}: the web's hatch tile only joins up at those angles`,
    );
  }
  out.push(`  --n-board-hatch-angle: ${board.hatch.angle}deg;`);
  out.push(`  --n-board-hatch-width: ${board.hatch.width / 16}rem;`);
  out.push(`  --n-board-hatch-opacity: ${board.hatch.opacity};`);
  // One line per square tile, corner to corner: `spacing` apart at 45°, and
  // a whole pixel wide so every tile draws the same and the lines can't band.
  // The web draws from the tile alone, so `spacing` isn't emitted itself.
  out.push(
    `  --n-board-hatch-tile: ${Math.round(board.hatch.spacing * Math.SQRT2) / 16}rem;`,
  );
  out.push("");
  const curve = tokens.motion.easeOutStrong.join(", ");
  for (const name of ["fast", "base", "slow"]) {
    out.push(`  --n-duration-${name}: ${tokens.motion[name]}ms;`);
  }
  out.push(`  --n-ease-out-strong: cubic-bezier(${curve});`);
  // A drag's tilt and lift: angles in degrees, the rest plain ratios.
  out.push(`  --n-tilt-max: ${tokens.motion.tiltMax}deg;`);
  out.push(`  --n-tilt-overshoot: ${tokens.motion.tiltOvershoot};`);
  out.push(`  --n-settle-overshoot: ${tokens.motion.settleOvershoot}deg;`);
  out.push(`  --n-settle-min-tilt: ${tokens.motion.settleMinTilt}deg;`);
  out.push(`  --n-lift: ${tokens.motion.lift};`);
  out.push("}", "", ".dark {");
  for (const [name, c] of entries(tokens.color)) {
    if (cssHex(c.dark, c, "dark") !== cssHex(c.light, c)) {
      out.push(`  --n-color-${kebab(name)}: ${cssHex(c.dark, c, "dark")};`);
    }
  }
  out.push(`  --n-sheet-shadow: ${cssSheetShadow(sheet, "dark")};`);
  out.push("}", "");
  const high = entries(tokens.color).filter(([, c]) => c.highContrast);
  if (high.length > 0) {
    out.push(
      "/* Increase Contrast (macOS, iOS) and its equivalents reach the web as",
      "   `prefers-contrast: more`: every colour with a highContrast value takes",
      "   it, as the Apple apps do. After the rules above, so it wins in both",
      "   modes; every highContrast has a light and a dark value. */",
      "@media (prefers-contrast: more) {",
      "  :root {",
    );
    for (const [name, c] of high) {
      out.push(
        `    --n-color-${kebab(name)}: ${cssHex(c.highContrast.light, c)};`,
      );
    }
    out.push("  }", "", "  .dark {");
    for (const [name, c] of high) {
      out.push(
        `    --n-color-${kebab(name)}: ${cssHex(c.highContrast.dark, c, "dark")};`,
      );
    }
    out.push("  }", "}", "");
  }
  return out.join("\n");
}

// Token names that are Swift keywords ("repeat") need backticks.
const SWIFT_KEYWORDS = new Set([
  "as", "break", "case", "catch", "class", "continue", "default", "defer",
  "do", "else", "enum", "extension", "fallthrough", "false", "for", "func",
  "guard", "if", "import", "in", "init", "is", "let", "nil", "operator",
  "protocol", "repeat", "return", "self", "static", "struct", "subscript",
  "super", "switch", "throw", "true", "try", "var", "where", "while",
]);
const swiftName = (name) => (SWIFT_KEYWORDS.has(name) ? `\`${name}\`` : name);

const swiftHex = (hex) => `0x${hex.replace("#", "").toUpperCase()}`;

const SWIFT_WEIGHTS = {
  100: "ultraLight",
  200: "thin",
  300: "light",
  400: "regular",
  500: "medium",
  600: "semibold",
  700: "bold",
  800: "heavy",
  900: "black",
};

/** tokens.json → Theme.swift */
export function renderSwift(tokens) {
  const out = [];
  out.push(...HEADER_LINES.map((l) => `// ${l}`), "");
  out.push(
    "import CoreText",
    "import SwiftUI",
    "#if os(macOS)",
    "import AppKit",
    "",
    "/// The platform's colour and font types, so the tokens below read the same",
    "/// on iOS and macOS. Only Theme and its extensions should need these.",
    "typealias PlatformColor = NSColor",
    "typealias PlatformFont = NSFont",
    "typealias PlatformFontDescriptor = NSFontDescriptor",
    "#else",
    "import UIKit",
    "",
    "typealias PlatformColor = UIColor",
    "typealias PlatformFont = UIFont",
    "typealias PlatformFontDescriptor = UIFontDescriptor",
    "#endif",
    "",
  );
  out.push(
    "/// Design tokens shared with the web app (src/shared/design/tokens.json).",
    "/// Views read colour, type, spacing and motion from here only.",
    "enum Theme {",
  );

  // Colors
  out.push(
    "    enum Colors {",
    "        /// A colour for light and dark mode, with optional Increase",
    "        /// Contrast variants that take over when that setting is on.",
    "        private static func dynamic(",
    "            light: UInt32,",
    "            dark: UInt32,",
    "            lightHighContrast: UInt32? = nil,",
    "            darkHighContrast: UInt32? = nil,",
    "            lightAlpha: CGFloat = 1,",
    "            darkAlpha: CGFloat = 1",
    "        ) -> Color {",
    "            let color = platformColor(",
    "                light: light, dark: dark, lightHighContrast: lightHighContrast, darkHighContrast: darkHighContrast,",
    "                lightAlpha: lightAlpha, darkAlpha: darkAlpha",
    "            )",
    "            #if os(macOS)",
    "            return Color(nsColor: color)",
    "            #else",
    "            return Color(uiColor: color)",
    "            #endif",
    "        }",
    "",
    "        /// The same colour as a dynamic `NSColor`/`UIColor`, resolved against",
    "        /// the appearance (macOS) or trait collection (iOS) it's drawn in.",
    "        /// `lightAlpha` and `darkAlpha` are for a token whose alpha differs",
    "        /// by appearance.",
    "        static func platformColor(",
    "            light: UInt32,",
    "            dark: UInt32,",
    "            lightHighContrast: UInt32? = nil,",
    "            darkHighContrast: UInt32? = nil,",
    "            lightAlpha: CGFloat = 1,",
    "            darkAlpha: CGFloat = 1",
    "        ) -> PlatformColor {",
    "            func resolve(isDark: Bool, isHighContrast: Bool) -> PlatformColor {",
    "                rgb(hex(",
    "                    light: light, dark: dark, lightHighContrast: lightHighContrast, darkHighContrast: darkHighContrast,",
    "                    isDark: isDark, isHighContrast: isHighContrast",
    "                ), alpha: isDark ? darkAlpha : lightAlpha)",
    "            }",
    "            #if os(macOS)",
    "            return NSColor(name: nil) { appearance in",
    "                let match = appearance.bestMatch(from: [",
    "                    .aqua, .darkAqua, .accessibilityHighContrastAqua, .accessibilityHighContrastDarkAqua",
    "                ])",
    "                // Increase Contrast reaches a window as a high-contrast",
    "                // variant of its appearance; the workspace flag covers views",
    "                // drawn outside one (a widget, an offscreen render).",
    "                let isHighContrast = match == .accessibilityHighContrastAqua",
    "                    || match == .accessibilityHighContrastDarkAqua",
    "                    || NSWorkspace.shared.accessibilityDisplayShouldIncreaseContrast",
    "                return resolve(",
    "                    isDark: match == .darkAqua || match == .accessibilityHighContrastDarkAqua,",
    "                    isHighContrast: isHighContrast",
    "                )",
    "            }",
    "            #else",
    "            return UIColor { traits in",
    "                resolve(isDark: traits.userInterfaceStyle == .dark, isHighContrast: traits.accessibilityContrast == .high)",
    "            }",
    "            #endif",
    "        }",
    "",
    "        // swiftlint:disable function_parameter_count",
    "        /// Which of a token's values applies: the high-contrast one when",
    "        /// Increase Contrast is on and the token has one, else light or dark.",
    "        static func hex(",
    "            light: UInt32,",
    "            dark: UInt32,",
    "            lightHighContrast: UInt32?,",
    "            darkHighContrast: UInt32?,",
    "            isDark: Bool,",
    "            isHighContrast: Bool",
    "        ) -> UInt32 {",
    "            if isHighContrast, let high = isDark ? darkHighContrast : lightHighContrast {",
    "                return high",
    "            }",
    "            return isDark ? dark : light",
    "        }",
    "        // swiftlint:enable function_parameter_count",
    "",
    "        private static func rgb(_ hex: UInt32, alpha: CGFloat) -> PlatformColor {",
    "            PlatformColor(",
    "                red: CGFloat((hex >> 16) & 0xFF) / 255,",
    "                green: CGFloat((hex >> 8) & 0xFF) / 255,",
    "                blue: CGFloat(hex & 0xFF) / 255,",
    "                alpha: alpha",
    "            )",
    "        }",
    "",
  );
  for (const [name, c] of entries(tokens.color)) {
    out.push(`        /// ${c.usage} (${c.source})`);
    const high = c.highContrast
      ? `, lightHighContrast: ${swiftHex(c.highContrast.light)}, darkHighContrast: ${swiftHex(c.highContrast.dark)}`
      : "";
    // One alpha for both appearances is an opacity; one per appearance goes
    // into the dynamic colour.
    const perMode = typeof c.alpha === "object";
    const alphas = perMode
      ? `, lightAlpha: ${c.alpha.light}, darkAlpha: ${c.alpha.dark}`
      : "";
    const opacity =
      c.alpha === undefined || perMode ? "" : `.opacity(${c.alpha})`;
    out.push(
      `        static let ${name} = dynamic(light: ${swiftHex(c.light)}, dark: ${swiftHex(c.dark)}${high}${alphas})${opacity}`,
    );
  }
  out.push("    }", "");

  // Fonts
  const display = tokens.font.display;
  out.push(
    "    enum Fonts {",
    `        /// Family name of the bundled display face (a variable font). Falls`,
    `        /// back to the system font when it isn't bundled.`,
    `        static let displayFontFamily = "${display.iosFamilyName}"`,
    "",
    "        /// The variable-font attribute and its `wght` axis ('wght' as a",
    "        /// four-char code). A weight trait alone leaves a variable face at",
    "        /// its default instance, so the weight is set on the axis instead.",
    "        static let variationAttribute = PlatformFontDescriptor.AttributeName(rawValue: kCTFontVariationAttribute as String)",
    "        static let weightAxis = 0x7767_6874",
    "",
    "        struct Style: Sendable {",
    "            let size: CGFloat",
    "            let lineHeight: CGFloat",
    "            let weight: PlatformFont.Weight",
    "            /// The same weight on the 100–900 scale, for the variable axis.",
    "            let variationWeight: CGFloat",
    "            let isDisplay: Bool",
    "            let textStyle: PlatformFont.TextStyle",
    "",
    "            /// The face at its base size, before Dynamic Type scaling.",
    "            var baseFont: PlatformFont {",
    "                if isDisplay {",
    "                    let descriptor = PlatformFontDescriptor(fontAttributes: [",
    "                        .family: Fonts.displayFontFamily,",
    "                        Fonts.variationAttribute: [Fonts.weightAxis: variationWeight]",
    "                    ])",
    "                    let face: PlatformFont? = PlatformFont(descriptor: descriptor, size: size)",
    "                    if let face, face.familyName == Fonts.displayFontFamily { return face }",
    "                }",
    "                return PlatformFont.systemFont(ofSize: size, weight: weight)",
    "            }",
    "",
    "            /// Scaled with Dynamic Type through `UIFontMetrics`, so each size",
    "            /// follows its matching text style. macOS has no Dynamic Type, so",
    "            /// there it's the base face.",
    "            var uiFont: PlatformFont {",
    "                #if os(macOS)",
    "                baseFont",
    "                #else",
    "                UIFontMetrics(forTextStyle: textStyle).scaledFont(for: baseFont)",
    "                #endif",
    "            }",
    "",
    "            var font: Font { Font(uiFont) }",
    "        }",
    "",
  );
  for (const [density, styles] of entries(tokens.type)) {
    out.push(`        enum ${density[0].toUpperCase()}${density.slice(1)} {`);
    for (const [name, t] of entries(styles)) {
      out.push(
        `            static let ${name} = Style(size: ${t.size}, lineHeight: ${t.lineHeight}, weight: .${SWIFT_WEIGHTS[t.weight]}, variationWeight: ${t.weight}, isDisplay: ${t.font === "display"}, textStyle: .${t.iosTextStyle})`,
      );
    }
    out.push("        }");
  }
  out.push("    }", "");

  // Spacing / radii
  out.push("    enum Space {");
  for (const [step, px] of entries(tokens.space.scale)) {
    out.push(`        static let s${step}: CGFloat = ${px}`);
  }
  out.push(
    `        static let rowMinHeight: CGFloat = ${tokens.space.rowMinHeight}`,
  );
  out.push("    }", "", "    enum Radius {");
  for (const [name, px] of entries(tokens.radius)) {
    out.push(`        static let ${name}: CGFloat = ${px}`);
  }
  out.push("    }", "");

  // Motion
  const [x1, y1, x2, y2] = tokens.motion.easeOutStrong;
  out.push("    enum Motion {");
  for (const name of ["fast", "base", "slow"]) {
    out.push(
      `        static let ${name}: TimeInterval = ${tokens.motion[name] / 1000}`,
    );
  }
  out.push(
    "",
    "        /// A drag's tilt: one angle per drag, at random within ±`tiltMax`",
    "        /// degrees, overshooting to `tiltOvershoot` times it on the way. The",
    "        /// landed row swings `settleOvershoot` degrees past level, unless it",
    "        /// was tilted less than `settleMinTilt`. The lifted todo scales to `lift`.",
    `        static let tiltMax: Double = ${tokens.motion.tiltMax}`,
    `        static let tiltOvershoot: Double = ${tokens.motion.tiltOvershoot}`,
    `        static let settleOvershoot: Double = ${tokens.motion.settleOvershoot}`,
    `        static let settleMinTilt: Double = ${tokens.motion.settleMinTilt}`,
    `        static let lift: CGFloat = ${tokens.motion.lift}`,
    "",
    "        /// The shared ease-out-strong curve at a token duration.",
    "        static func easeOutStrong(_ duration: TimeInterval = base) -> Animation {",
    `            .timingCurve(${x1}, ${y1}, ${x2}, ${y2}, duration: duration)`,
    "        }",
    "    }",
    "",
  );

  // Icons
  out.push(
    "    /// SF Symbol names, keyed the same as the lucide icons on web.",
    "    enum Icon {",
  );
  for (const [name, icon] of entries(tokens.icons)) {
    out.push(
      `        static let ${swiftName(name)} = "${icon.sfSymbol}" // lucide: ${icon.lucide}`,
    );
  }
  out.push("    }", "}", "");
  return out.join("\n");
}

export function renderAll(tokens = loadTokens()) {
  return { css: renderCss(tokens), swift: renderSwift(tokens) };
}

/** Paths whose committed content differs from what tokens.json renders. */
export function staleOutputs(rendered = renderAll()) {
  return Object.entries(OUTPUTS)
    .filter(([kind, path]) => {
      try {
        return readFileSync(path, "utf8") !== rendered[kind];
      } catch {
        return true;
      }
    })
    .map(([, path]) => path);
}

function main() {
  const check = process.argv.includes("--check");
  const rendered = renderAll();
  if (check) {
    const stale = staleOutputs(rendered);
    if (stale.length > 0) {
      console.error("✗ Design tokens are out of date:");
      for (const path of stale) console.error(`  ${relative(REPO_ROOT, path)}`);
      console.error("Run `bun run tokens` and commit the result.");
      process.exit(1);
    }
    console.log("✓ Generated design tokens are up to date");
    return;
  }
  for (const [kind, path] of Object.entries(OUTPUTS)) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, rendered[kind]);
    console.log(`wrote ${relative(REPO_ROOT, path)}`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}

#!/usr/bin/env node
/**
 * Generates platform token files from tokens.json:
 *
 *   src/web/src/styles/tokens.css                       CSS custom properties
 *   src/ios/Nylon Impossible/Nylon Impossible/Theme/Theme.swift
 *
 *   node src/shared/design/generate.mjs           write both files
 *   node src/shared/design/generate.mjs --check   exit 1 if either is stale
 *
 * Plain Node, no dependencies. The render functions are exported so the token
 * test can check them without touching the filesystem.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = join(here, "../../..");
export const TOKENS_PATH = join(here, "tokens.json");
export const OUTPUTS = {
  css: join(REPO_ROOT, "src/web/src/styles/tokens.css"),
  swift: join(
    REPO_ROOT,
    "src/ios/Nylon Impossible/Nylon Impossible/Theme/Theme.swift",
  ),
};

const HEADER_LINES = [
  "Generated by src/shared/design/generate.mjs from tokens.json — do not edit.",
  "Change tokens.json, then run `bun run tokens`. `bun run tokens:check` fails CI",
  "when this file is stale.",
];

export function loadTokens() {
  return JSON.parse(readFileSync(TOKENS_PATH, "utf8"));
}

const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const entries = (obj) =>
  Object.entries(obj).filter(([key]) => !key.startsWith("$"));

function cssFontFamily(tokens, fontKey) {
  const font = tokens.font[fontKey];
  const system = "ui-sans-serif, system-ui, -apple-system, sans-serif";
  return font.family === "system" ? system : `"${font.family}", ${system}`;
}

/** tokens.json → tokens.css */
export function renderCss(tokens) {
  const out = [];
  out.push("/*", ...HEADER_LINES.map((l) => ` * ${l}`), " */", "");
  out.push(
    "/* Every token is prefixed --n- so it can't collide with Tailwind's own",
    "   theme variables. Dark values apply under the same class-based variant",
    "   the app uses (`.dark` on <html>, set by SSR and ThemeSync). */",
    ":root {",
  );
  for (const [name, c] of entries(tokens.color)) {
    out.push(`  --n-color-${kebab(name)}: ${c.light.toLowerCase()};`);
  }
  out.push("");
  for (const [name] of entries(tokens.font)) {
    out.push(`  --n-font-${kebab(name)}: ${cssFontFamily(tokens, name)};`);
  }
  out.push("");
  for (const [density, styles] of entries(tokens.type)) {
    for (const [name, t] of entries(styles)) {
      const p = `--n-type-${density}-${kebab(name)}`;
      out.push(`  ${p}-font: var(--n-font-${t.font});`);
      out.push(`  ${p}-size: ${t.size / 16}rem;`);
      out.push(`  ${p}-line-height: ${t.lineHeight / 16}rem;`);
      out.push(`  ${p}-weight: ${t.weight};`);
    }
  }
  out.push("");
  for (const [step, px] of entries(tokens.space.scale)) {
    out.push(`  --n-space-${step}: ${px / 16}rem;`);
  }
  out.push(`  --n-row-min-height: ${tokens.space.rowMinHeight / 16}rem;`);
  out.push("");
  for (const [name, px] of entries(tokens.radius)) {
    out.push(`  --n-radius-${kebab(name)}: ${px / 16}rem;`);
  }
  out.push("");
  const curve = tokens.motion.easeOutStrong.join(", ");
  for (const name of ["fast", "base", "slow"]) {
    out.push(`  --n-duration-${name}: ${tokens.motion[name]}ms;`);
  }
  out.push(`  --n-ease-out-strong: cubic-bezier(${curve});`);
  out.push("}", "", ".dark {");
  for (const [name, c] of entries(tokens.color)) {
    if (c.dark.toLowerCase() !== c.light.toLowerCase()) {
      out.push(`  --n-color-${kebab(name)}: ${c.dark.toLowerCase()};`);
    }
  }
  out.push("}", "");
  return out.join("\n");
}

// Token names that are Swift keywords ("repeat") need backticks.
const SWIFT_KEYWORDS = new Set([
  "as", "break", "case", "catch", "class", "continue", "default", "defer",
  "do", "else", "enum", "extension", "fallthrough", "false", "for", "func",
  "guard", "if", "import", "in", "init", "is", "let", "nil", "operator",
  "protocol", "repeat", "return", "self", "static", "struct", "subscript",
  "super", "switch", "throw", "true", "try", "var", "where", "while",
]);
const swiftName = (name) => (SWIFT_KEYWORDS.has(name) ? `\`${name}\`` : name);

const swiftHex = (hex) => `0x${hex.replace("#", "").toUpperCase()}`;

const SWIFT_WEIGHTS = {
  100: "ultraLight",
  200: "thin",
  300: "light",
  400: "regular",
  500: "medium",
  600: "semibold",
  700: "bold",
  800: "heavy",
  900: "black",
};

/** tokens.json → Theme.swift */
export function renderSwift(tokens) {
  const out = [];
  out.push(...HEADER_LINES.map((l) => `// ${l}`), "");
  out.push("import CoreText", "import SwiftUI", "import UIKit", "");
  out.push(
    "/// Design tokens shared with the web app (src/shared/design/tokens.json).",
    "/// Views read colour, type, spacing and motion from here only.",
    "enum Theme {",
  );

  // Colors
  out.push(
    "    enum Colors {",
    "        private static func dynamic(light: UInt32, dark: UInt32) -> Color {",
    "            Color(uiColor: UIColor { traits in",
    "                rgb(traits.userInterfaceStyle == .dark ? dark : light)",
    "            })",
    "        }",
    "",
    "        private static func rgb(_ hex: UInt32) -> UIColor {",
    "            UIColor(",
    "                red: CGFloat((hex >> 16) & 0xFF) / 255,",
    "                green: CGFloat((hex >> 8) & 0xFF) / 255,",
    "                blue: CGFloat(hex & 0xFF) / 255,",
    "                alpha: 1",
    "            )",
    "        }",
    "",
  );
  for (const [name, c] of entries(tokens.color)) {
    out.push(`        /// ${c.usage} (${c.source})`);
    out.push(
      `        static let ${name} = dynamic(light: ${swiftHex(c.light)}, dark: ${swiftHex(c.dark)})`,
    );
  }
  out.push("    }", "");

  // Fonts
  const display = tokens.font.display;
  out.push(
    "    enum Fonts {",
    `        /// Family name of the bundled display face (a variable font). Falls`,
    `        /// back to the system font when it isn't bundled.`,
    `        static let displayFontFamily = "${display.iosFamilyName}"`,
    "",
    "        /// The variable-font attribute and its `wght` axis ('wght' as a",
    "        /// four-char code). A weight trait alone leaves a variable face at",
    "        /// its default instance, so the weight is set on the axis instead.",
    "        static let variationAttribute = UIFontDescriptor.AttributeName(rawValue: kCTFontVariationAttribute as String)",
    "        static let weightAxis = 0x7767_6874",
    "",
    "        struct Style: Sendable {",
    "            let size: CGFloat",
    "            let lineHeight: CGFloat",
    "            let weight: UIFont.Weight",
    "            /// The same weight on the 100–900 scale, for the variable axis.",
    "            let variationWeight: CGFloat",
    "            let isDisplay: Bool",
    "            let textStyle: UIFont.TextStyle",
    "",
    "            /// The face at its base size, before Dynamic Type scaling.",
    "            var baseFont: UIFont {",
    "                if isDisplay {",
    "                    let descriptor = UIFontDescriptor(fontAttributes: [",
    "                        .family: Fonts.displayFontFamily,",
    "                        Fonts.variationAttribute: [Fonts.weightAxis: variationWeight]",
    "                    ])",
    "                    let face = UIFont(descriptor: descriptor, size: size)",
    "                    if face.familyName == Fonts.displayFontFamily { return face }",
    "                }",
    "                return UIFont.systemFont(ofSize: size, weight: weight)",
    "            }",
    "",
    "            /// Scaled with Dynamic Type through `UIFontMetrics`, so each size",
    "            /// follows its matching text style.",
    "            var uiFont: UIFont {",
    "                UIFontMetrics(forTextStyle: textStyle).scaledFont(for: baseFont)",
    "            }",
    "",
    "            var font: Font { Font(uiFont) }",
    "        }",
    "",
  );
  for (const [density, styles] of entries(tokens.type)) {
    out.push(`        enum ${density[0].toUpperCase()}${density.slice(1)} {`);
    for (const [name, t] of entries(styles)) {
      out.push(
        `            static let ${name} = Style(size: ${t.size}, lineHeight: ${t.lineHeight}, weight: .${SWIFT_WEIGHTS[t.weight]}, variationWeight: ${t.weight}, isDisplay: ${t.font === "display"}, textStyle: .${t.iosTextStyle})`,
      );
    }
    out.push("        }");
  }
  out.push("    }", "");

  // Spacing / radii
  out.push("    enum Space {");
  out.push(`        static let unit: CGFloat = ${tokens.space.unit}`);
  for (const [step, px] of entries(tokens.space.scale)) {
    out.push(`        static let s${step}: CGFloat = ${px}`);
  }
  out.push(
    `        static let rowMinHeight: CGFloat = ${tokens.space.rowMinHeight}`,
  );
  out.push("    }", "", "    enum Radius {");
  for (const [name, px] of entries(tokens.radius)) {
    out.push(`        static let ${name}: CGFloat = ${px}`);
  }
  out.push("    }", "");

  // Motion
  const [x1, y1, x2, y2] = tokens.motion.easeOutStrong;
  out.push("    enum Motion {");
  for (const name of ["fast", "base", "slow"]) {
    out.push(
      `        static let ${name}: TimeInterval = ${tokens.motion[name] / 1000}`,
    );
  }
  out.push(
    "",
    "        /// The shared ease-out-strong curve at a token duration.",
    "        static func easeOutStrong(_ duration: TimeInterval = base) -> Animation {",
    `            .timingCurve(${x1}, ${y1}, ${x2}, ${y2}, duration: duration)`,
    "        }",
    "    }",
    "",
  );

  // Icons
  out.push(
    "    /// SF Symbol names, keyed the same as the lucide icons on web.",
    "    enum Icon {",
  );
  for (const [name, icon] of entries(tokens.icons)) {
    out.push(
      `        static let ${swiftName(name)} = "${icon.sfSymbol}" // lucide: ${icon.lucide}`,
    );
  }
  out.push("    }", "}", "");
  return out.join("\n");
}

export function renderAll(tokens = loadTokens()) {
  return { css: renderCss(tokens), swift: renderSwift(tokens) };
}

/** Paths whose committed content differs from what tokens.json renders. */
export function staleOutputs(rendered = renderAll()) {
  return Object.entries(OUTPUTS)
    .filter(([kind, path]) => {
      try {
        return readFileSync(path, "utf8") !== rendered[kind];
      } catch {
        return true;
      }
    })
    .map(([, path]) => path);
}

function main() {
  const check = process.argv.includes("--check");
  const rendered = renderAll();
  if (check) {
    const stale = staleOutputs(rendered);
    if (stale.length > 0) {
      console.error("✗ Design tokens are out of date:");
      for (const path of stale) console.error(`  ${relative(REPO_ROOT, path)}`);
      console.error("Run `bun run tokens` and commit the result.");
      process.exit(1);
    }
    console.log("✓ Generated design tokens are up to date");
    return;
  }
  for (const [kind, path] of Object.entries(OUTPUTS)) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, rendered[kind]);
    console.log(`wrote ${relative(REPO_ROOT, path)}`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
